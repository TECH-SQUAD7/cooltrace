// Shared browser helpers for screenshots and footage capture.
import { chromium } from 'playwright-core';
import fs from 'node:fs';

const CANDIDATES = [
  process.env.CHROME_PATH,
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
].filter(Boolean);

export const APP_URL = process.env.APP_URL || 'http://localhost:8787';
export const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export async function launch({ width = 1920, height = 1080, scale = 1, headless = true } = {}) {
  const executablePath = CANDIDATES.find((p) => fs.existsSync(p));
  if (!executablePath) throw new Error('Chrome/Edge not found. Set CHROME_PATH.');
  const browser = await chromium.launch({ executablePath, headless, args: ['--hide-scrollbars', '--force-color-profile=srgb'] });
  const context = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: scale, colorScheme: 'light' });
  const page = await context.newPage();
  return { browser, context, page };
}

export async function openApp(page, city = 'madrid') {
  await page.goto(APP_URL, { waitUntil: 'networkidle' });
  await page.waitForSelector('text=Heat in', { timeout: 60000 });
  await page.waitForFunction(() => document.body.innerText.includes('Land cover from') || document.body.innerText.includes('Synthetic land cover'), null, { timeout: 180000 });
  if (city) {
    await page.selectOption('select[aria-label="City"]', city);
    await page.waitForFunction(() => !document.body.innerText.includes('Mapping heat in'), null, { timeout: 180000 });
    await page.waitForTimeout(800);
  }
  await page.evaluate(() => document.fonts.ready);
}

export async function nav(page, label) {
  await page.locator('nav[aria-label="Sections"] button', { hasText: label }).first().click();
  await page.waitForTimeout(600);
}

/** Wait until map tiles under the overlay have loaded. */
export async function tilesSettled(page, ms = 15000) {
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile')].every((t) => t.complete), null, { timeout: ms }).catch(() => {});
  await page.waitForTimeout(300);
}

export async function clickAI(page, text, { timeout = 90000 } = {}) {
  const btn = page.locator('button', { hasText: text }).first();
  await btn.click();
  await page.waitForFunction(() => document.body.innerText.includes('Generated by') || document.body.innerText.includes('AI request failed'), null, { timeout });
}
