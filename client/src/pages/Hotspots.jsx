import { useEffect, useMemo, useState } from 'react';
import { ResponsiveContainer, BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, Legend } from 'recharts';
import { Flame, Sparkles, Target, Zap, ShieldAlert, ArrowRight } from 'lucide-react';
import { useApp, aiContext } from '../state.jsx';
import HeatMap from '../components/HeatMap.jsx';
import { Card, Segmented, AIButton, ErrorBanner, List, Spinner, Notice } from '../components/ui.jsx';
import { layerData } from '../lib/layers.js';
import { useAI } from '../components/useAI.js';
import { axis, gridProps, tooltipProps, legendProps } from '../components/charts.jsx';
import { fmtC, fmtNum, fmtPct } from '../lib/format.js';

const IMPACT = { high: 'bg-hot/10 text-hot', medium: 'bg-warn/10 text-warn', low: 'bg-raised text-ink-2' };

function HotspotAI({ zone }) {
  const app = useApp();
  const key = `hotspot:${app.city.name}:${app.scenario.id}:${app.hotspotVar}:${zone.id}:${zone.cells}`;
  const { data, loading, error, run } = useAI(key, 'hotspot');
  const r = data?.result;

  const generate = () => {
    const ctx = aiContext(app);
    const { cellIds, bounds, ...hotspot } = zone;
    run({ city: ctx.city, hotspot: { ...hotspot, detectionVariable: app.hotspotVar }, cityStats: ctx.cityStats, weather: ctx.weather, provenance: ctx.provenance });
  };

  return (
    <Card
      title={`AI explanation · ${zone.name}`}
      icon={Sparkles}
      actions={<AIButton onClick={generate} loading={loading} aiReady={app.aiReady}>{r ? 'Regenerate' : 'Explain with Gemini'}</AIButton>}
    >
      {!app.aiReady && <Notice tone="warn">Add your Gemini API key on the server to enable AI explanations.</Notice>}
      {loading && <Spinner label="Gemini is analysing the hotspot drivers…" />}
      <ErrorBanner error={error} title="AI request failed" onRetry={generate} />
      {!r && !loading && !error && app.aiReady && (
        <p className="text-sm text-ink-3">Gemini will interpret the locally computed metrics for this zone and propose targeted cooling actions.</p>
      )}
      {r && !loading && (
        <div className="space-y-4">
          <p className="text-sm leading-relaxed text-ink">{r.summary}</p>
          {Array.isArray(r.drivers) && r.drivers.length > 0 && (
            <div>
              <div className="label mb-2">Heat drivers</div>
              <div className="space-y-2">
                {r.drivers.map((d, i) => (
                  <div key={i} className="rounded-[3px] border border-rule bg-raised/60 p-2.5">
                    <div className="flex items-center justify-between gap-2">
                      <span className="text-sm font-medium text-ink">{d.factor}</span>
                      {d.impact && <span className={`rounded px-1.5 py-0.5 text-[10px] font-semibold  ${IMPACT[d.impact] || IMPACT.low}`}>{d.impact}</span>}
                    </div>
                    <div className="mt-1 text-xs text-ink-3">{d.evidence}</div>
                  </div>
                ))}
              </div>
            </div>
          )}
          {Array.isArray(r.recommendations) && (
            <div>
              <div className="label mb-2">Recommended interventions</div>
              <div className="space-y-2">
                {r.recommendations.map((x, i) => (
                  <div key={i} className="rounded-[3px] border border-rule bg-raised/60 p-2.5">
                    <div className="flex items-start gap-2">
                      <span className="grid h-5 w-5 shrink-0 place-items-center rounded-full bg-accent text-[11px] font-bold text-white">{x.priority ?? i + 1}</span>
                      <div className="flex-1">
                        <div className="text-sm font-medium text-ink">{x.action}</div>
                        <div className="mt-0.5 text-xs text-ink-3">{x.rationale}</div>
                        <div className="mt-1.5 flex flex-wrap gap-1.5 text-[11px]">
                          {x.expectedCooling && <span className="rounded bg-accent/10 px-1.5 py-0.5 text-accent">↓ {x.expectedCooling}</span>}
                          {x.cost && <span className="rounded bg-raised px-1.5 py-0.5 text-ink-2">cost: {x.cost}</span>}
                          {x.timeframe && <span className="rounded bg-raised px-1.5 py-0.5 text-ink-2">{x.timeframe}</span>}
                        </div>
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            </div>
          )}
          {r.risks?.length > 0 && (<div><div className="label mb-2 flex items-center gap-1"><ShieldAlert className="h-3 w-3" /> Risks</div><List items={r.risks} /></div>)}
          {r.quickWins?.length > 0 && (<div><div className="label mb-2 flex items-center gap-1"><Zap className="h-3 w-3" /> Quick wins</div><List items={r.quickWins} /></div>)}
          <div className="text-[11px] text-ink-3">Generated by {data.model} · {new Date(data.generatedAt).toLocaleString()} · AI text interprets modelled estimates; verify before acting.</div>
        </div>
      )}
    </Card>
  );
}

export default function Hotspots({ goTo }) {
  const app = useApp();
  const { grid, baseline, features, z, zones, hotspotVar, setHotspotVar, setOptSettings } = app;
  const [sel, setSel] = useState(zones[0]?.id ?? null);
  useEffect(() => { if (!zones.find((x) => x.id === sel)) setSel(zones[0]?.id ?? null); }, [zones, sel]);
  const zone = zones.find((x) => x.id === sel);
  const L = useMemo(() => layerData('gi', { model: baseline, features, z }), [baseline, features, z]);
  const s = baseline.stats;

  const compare = zone && [
    { metric: 'Impervious', Zone: zone.impervious * 100, City: s.meanImpervious * 100 },
    { metric: 'Roofs', Zone: zone.roof * 100, City: (features.reduce((a, f) => a + f.roof, 0) / features.length) * 100 },
    { metric: 'Roads', Zone: zone.road * 100, City: (features.reduce((a, f) => a + f.road, 0) / features.length) * 100 },
    { metric: 'Vegetation', Zone: zone.vegetation * 100, City: (features.reduce((a, f) => a + f.veg, 0) / features.length) * 100 },
    { metric: 'Canopy', Zone: zone.canopy * 100, City: s.meanCanopy * 100 },
  ].map((r) => ({ ...r, Zone: +r.Zone.toFixed(1), City: +r.City.toFixed(1) }));

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-3">
        <span className="text-sm text-ink-3">Detect hotspots on:</span>
        <Segmented
          options={[{ value: 'surface', label: 'Surface temp' }, { value: 'air', label: 'Air temp' }, { value: 'felt', label: 'Felt temp' }, { value: 'hvi', label: 'Vulnerability' }]}
          value={hotspotVar}
          onChange={setHotspotVar}
        />
        <span className="text-xs text-ink-3">Getis-Ord Gi* · 5×5 cell (~625 m) distance band · 95% confidence · computed locally</span>
        <button
          className="btn-ghost ml-auto"
          disabled={!zones.length}
          onClick={() => { setOptSettings((o) => ({ ...o, strategy: 'hotspots' })); goTo('optimiser'); }}
        >
          <Target className="h-4 w-4" /> Optimise budget for hotspots <ArrowRight className="h-4 w-4" />
        </button>
      </div>

      <div className="grid gap-4 xl:grid-cols-[1fr_420px]">
        <Card title="Hot & cool spots (Gi* z-score)" icon={Flame} bodyClass="p-3">
          <HeatMap grid={grid} values={L.values} ramp={L.ramp} domain={L.domain} label={L.label} format={L.format} zones={zones} selectedZone={sel} onZoneClick={setSel}
            onCellClick={(k) => { const zz = zones.find((x) => x.cellIds.includes(k)); if (zz) setSel(zz.id); }} smooth={false} height={520} />
        </Card>
        <Card title={`${zones.length} hotspot zones (ranked by severity)`} icon={Target} bodyClass="max-h-[586px] overflow-y-auto p-2">
          {!zones.length && <p className="p-3 text-sm text-ink-3">No statistically significant hotspot clusters for this variable and scenario.</p>}
          <div className="space-y-1.5">
            {zones.map((zn) => (
              <button
                key={zn.id}
                onClick={() => setSel(zn.id)}
                className={`w-full rounded-[3px] border p-2.5 text-left transition ${zn.id === sel ? 'border-accent bg-accent/10' : 'border-rule bg-raised/60 hover:border-ink-3'}`}
              >
                <div className="flex items-center justify-between">
                  <span className="font-semibold text-ink">{zn.name}</span>
                  <span className="rounded bg-hot/10 px-1.5 py-0.5 text-[11px] font-semibold text-hot">severity {zn.severity}</span>
                </div>
                <div className="mt-1 grid grid-cols-3 gap-1 text-xs text-ink-3">
                  <span>{zn.areaHa} ha</span>
                  <span>surf {zn.meanSurface}°</span>
                  <span>felt {zn.meanFelt}°</span>
                  <span>HVI {zn.meanHVI}</span>
                  <span>z̄ {zn.meanZ}</span>
                  <span>{fmtNum(zn.populationProxy)} ppl</span>
                </div>
              </button>
            ))}
          </div>
        </Card>
      </div>

      {zone && (
        <div className="grid gap-4 xl:grid-cols-[420px_1fr]">
          <div className="space-y-4">
            <Card title={`${zone.name} profile`} icon={Flame}>
              <div className="grid grid-cols-2 gap-2 text-sm">
                {[
                  ['Area', `${zone.areaHa} ha (${zone.cells} cells)`],
                  ['Mean surface', fmtC(zone.meanSurface)],
                  ['Peak surface', fmtC(zone.maxSurface)],
                  ['Mean air', fmtC(zone.meanAir, 2)],
                  ['Felt temp', fmtC(zone.meanFelt)],
                  ['Vulnerability', `${zone.meanHVI} / 100`],
                  ['Impervious', fmtPct(zone.impervious)],
                  ['Canopy', fmtPct(zone.canopy)],
                  ['Buildings', fmtNum(zone.buildings)],
                  ['People (proxy)', fmtNum(zone.populationProxy)],
                ].map(([k, v]) => (
                  <div key={k} className="rounded-[3px] bg-raised/60 px-2.5 py-1.5"><div className="text-[11px] text-ink-3">{k}</div><div className="font-medium text-ink">{v}</div></div>
                ))}
              </div>
              <div className="mt-3 text-xs text-ink-3">
                vs city mean: surface <span className="text-hot">+{(zone.meanSurface - s.meanSurface).toFixed(1)} °C</span>, air <span className="text-hot">+{(zone.meanAir - s.meanAir).toFixed(2)} °C</span>
              </div>
            </Card>
            <Card title="Land cover vs city average (%)" bodyClass="p-2">
              <div className="h-56">
                <ResponsiveContainer>
                  <BarChart data={compare} margin={{ top: 8, right: 8, left: -20, bottom: 0 }}>
                    <CartesianGrid {...gridProps} />
                    <XAxis dataKey="metric" {...axis} />
                    <YAxis {...axis} />
                    <Tooltip {...tooltipProps} formatter={(v) => `${v}%`} />
                    <Legend {...legendProps} />
                    <Bar isAnimationActive={false} dataKey="Zone" fill="#e8833a" radius={[3, 3, 0, 0]} />
                    <Bar isAnimationActive={false} dataKey="City" fill="#9aa5ab" radius={[3, 3, 0, 0]} />
                  </BarChart>
                </ResponsiveContainer>
              </div>
            </Card>
          </div>
          <HotspotAI zone={zone} />
        </div>
      )}
    </div>
  );
}
